package main

import (
	"fmt"
	"path"
	"strings"
	"unicode"

	protocolv1 "github.com/cnooljaw/gsr/protocol/gen/go/gsr/protocol/v1"
	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/proto"
	"google.golang.org/protobuf/reflect/protoreflect"
)

const catalogImportPath = "github.com/cnooljaw/gsr/protocol/catalog"

func main() {
	var modulePath string
	options := protogen.Options{ParamFunc: func(name, value string) error {
		if name != "module_path" {
			return fmt.Errorf("unknown generator option %q", name)
		}
		modulePath = value
		return nil
	}}
	options.Run(func(plugin *protogen.Plugin) error {
		return generate(plugin, modulePath)
	})
}

func generate(plugin *protogen.Plugin, modulePath string) error {
	messages := make(map[protoreflect.FullName]*protogen.Message)
	for _, file := range plugin.Files {
		collectMessages(file.Messages, messages)
	}

	for _, file := range plugin.Files {
		if !file.Generate {
			continue
		}
		if err := generateFile(plugin, file, messages, modulePath); err != nil {
			return err
		}
	}
	return nil
}

func generateFile(plugin *protogen.Plugin, file *protogen.File, messages map[protoreflect.FullName]*protogen.Message, modulePath string) error {
	var entries []generatedEntry
	for _, enum := range file.Enums {
		if enum.Desc.Name() != "MsgId" {
			continue
		}
		for _, value := range enum.Values {
			if value.Desc.Number() == 0 {
				if hasMessageRoute(value) {
					return fmt.Errorf("%s: MsgId.%s reserves zero and cannot have a route", file.Desc.Path(), value.Desc.Name())
				}
				continue
			}

			route, err := messageRoute(value)
			if err != nil {
				return fmt.Errorf("%s: MsgId.%s: %w", file.Desc.Path(), value.Desc.Name(), err)
			}
			payloadName := protoreflect.FullName(strings.TrimPrefix(route.GetPayloadType(), "."))
			message := messages[payloadName]
			if message == nil {
				return fmt.Errorf("%s: MsgId.%s refers to unknown payload type %q", file.Desc.Path(), value.Desc.Name(), route.GetPayloadType())
			}
			if message.Desc.IsMapEntry() {
				return fmt.Errorf("%s: MsgId.%s payload type %q is a generated map entry", file.Desc.Path(), value.Desc.Name(), route.GetPayloadType())
			}

			direction, err := generatedDirection(route.GetDirection())
			if err != nil {
				return fmt.Errorf("%s: MsgId.%s: %w", file.Desc.Path(), value.Desc.Name(), err)
			}
			kind, err := generatedKind(route.GetKind())
			if err != nil {
				return fmt.Errorf("%s: MsgId.%s: %w", file.Desc.Path(), value.Desc.Name(), err)
			}
			if direction == "ClientToServer" && kind != "Request" && kind != "Notify" {
				return fmt.Errorf("%s: MsgId.%s: client-to-server messages must be requests or notifications", file.Desc.Path(), value.Desc.Name())
			}
			if direction == "ServerToClient" && kind != "Response" && kind != "Push" {
				return fmt.Errorf("%s: MsgId.%s: server-to-client messages must be responses or pushes", file.Desc.Path(), value.Desc.Name())
			}
			entries = append(entries, generatedEntry{
				id:        value.GoIdent,
				message:   message.GoIdent,
				direction: direction,
				kind:      kind,
			})
		}
	}

	if len(entries) == 0 {
		return nil
	}
	return writeCatalog(plugin, file, entries, modulePath)
}

type generatedEntry struct {
	id        protogen.GoIdent
	message   protogen.GoIdent
	direction string
	kind      string
}

func writeCatalog(plugin *protogen.Plugin, file *protogen.File, entries []generatedEntry, modulePath string) error {
	outputPath, err := catalogOutputPath(file.Desc.Path(), string(file.GoImportPath), modulePath)
	if err != nil {
		return err
	}
	generated := plugin.NewGeneratedFile(outputPath, file.GoImportPath)
	catalogEntry := generated.QualifiedGoIdent(protogen.GoIdent{
		GoName:       "Entry",
		GoImportPath: protogen.GoImportPath(catalogImportPath),
	})
	protoMessage := generated.QualifiedGoIdent(protogen.GoIdent{
		GoName:       "Message",
		GoImportPath: "google.golang.org/protobuf/proto",
	})

	generated.P("// Code generated by protoc-gen-gsr-registry. DO NOT EDIT.")
	generated.P()
	generated.P("package ", file.GoPackageName)
	generated.P()
	generated.P("var ", catalogVariableName(file.Desc.Path()), " = []", catalogEntry, "{")
	for _, entry := range entries {
		direction := generated.QualifiedGoIdent(protogen.GoIdent{
			GoName:       entry.direction,
			GoImportPath: protogen.GoImportPath(catalogImportPath),
		})
		message := generated.QualifiedGoIdent(entry.message)
		id := generated.QualifiedGoIdent(entry.id)
		generated.P("{")
		generated.P("ID: uint32(", id, "),")
		generated.P("Direction: ", direction, ",")
		kind := generated.QualifiedGoIdent(protogen.GoIdent{
			GoName:       entry.kind,
			GoImportPath: protogen.GoImportPath(catalogImportPath),
		})
		generated.P("Kind: ", kind, ",")
		generated.P("NewMessage: func() ", protoMessage, " { return &", message, "{} },")
		generated.P("},")
	}
	generated.P("}")
	return nil
}

func catalogOutputPath(protoPath, importPath, modulePath string) (string, error) {
	outputPath := strings.TrimSuffix(protoPath, ".proto") + "_registry.pb.go"
	if modulePath != "" {
		modulePrefix := strings.TrimSuffix(modulePath, "/") + "/"
		if !strings.HasPrefix(importPath, modulePrefix) {
			return "", fmt.Errorf("%s: Go import path %q is outside module %q", protoPath, importPath, modulePath)
		}
		outputPath = path.Join(strings.TrimPrefix(importPath, modulePrefix),
			path.Base(outputPath))
	}
	return outputPath, nil
}

func messageRoute(value *protogen.EnumValue) (*protocolv1.MessageRoute, error) {
	options, ok := value.Desc.Options().(proto.Message)
	if !ok || !proto.HasExtension(options, protocolv1.E_MessageRoute) {
		return nil, fmt.Errorf("non-zero MsgId requires message_route payload metadata")
	}
	route, ok := proto.GetExtension(options, protocolv1.E_MessageRoute).(*protocolv1.MessageRoute)
	if !ok || route == nil {
		return nil, fmt.Errorf("message_route has an invalid value")
	}
	if route.GetPayloadType() == "" {
		return nil, fmt.Errorf("message_route payload_type is empty")
	}
	return route, nil
}

func hasMessageRoute(value *protogen.EnumValue) bool {
	options, ok := value.Desc.Options().(proto.Message)
	return ok && proto.HasExtension(options, protocolv1.E_MessageRoute)
}

func generatedDirection(direction protocolv1.Direction) (string, error) {
	switch direction {
	case protocolv1.Direction_DIRECTION_CLIENT_TO_SERVER:
		return "ClientToServer", nil
	case protocolv1.Direction_DIRECTION_SERVER_TO_CLIENT:
		return "ServerToClient", nil
	default:
		return "", fmt.Errorf("message_route direction must be specified")
	}
}

func generatedKind(kind protocolv1.Kind) (string, error) {
	switch kind {
	case protocolv1.Kind_KIND_REQUEST:
		return "Request", nil
	case protocolv1.Kind_KIND_NOTIFY:
		return "Notify", nil
	case protocolv1.Kind_KIND_RESPONSE:
		return "Response", nil
	case protocolv1.Kind_KIND_PUSH:
		return "Push", nil
	default:
		return "", fmt.Errorf("message_route kind must be specified")
	}
}

func collectMessages(messages []*protogen.Message, collected map[protoreflect.FullName]*protogen.Message) {
	for _, message := range messages {
		collected[message.Desc.FullName()] = message
		collectMessages(message.Messages, collected)
	}
}

func catalogVariableName(protoPath string) string {
	name := strings.TrimSuffix(protoPath, path.Ext(protoPath))
	var result strings.Builder
	result.WriteString("MessageCatalog")
	capitalizeNext := true
	for _, character := range name {
		if !unicode.IsLetter(character) && !unicode.IsDigit(character) {
			capitalizeNext = true
			continue
		}
		if capitalizeNext {
			result.WriteRune(unicode.ToUpper(character))
			capitalizeNext = false
			continue
		}
		result.WriteRune(character)
	}
	return result.String()
}
